using System.Net.Mime;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using Microsoft.AspNetCore.RateLimiting;
using ProductManagement.Api.Http;
using ProductManagement.Api.RateLimiting;
using ProductManagement.Api.Security;
using ProductManagement.Application.Common.Paging;
using ProductManagement.Application.Products;
using ProductManagement.Application.Products.Contracts;

namespace ProductManagement.Api.Controllers;

/// <summary>
/// Products and their stock.
/// </summary>
/// <remarks>
/// Controllers only translate HTTP into use-case calls and results back into HTTP. Validation, business rules and
/// persistence live in the application, domain and infrastructure layers.
/// <para>
/// Every endpoint needs <see cref="Policies.ProductsRead"/>; mutating endpoints additionally need a write
/// permission and use the stricter <see cref="RateLimitPolicies.Writes"/> rate limit.
/// </para>
/// </remarks>
[Route("api/products")]
[Authorize(Policy = Policies.ProductsRead)]
[ProducesResponseType<ProblemDetails>(StatusCodes.Status401Unauthorized, ProblemJsonContentType)]
[ProducesResponseType<ProblemDetails>(StatusCodes.Status403Forbidden, ProblemJsonContentType)]
[ProducesResponseType<ProblemDetails>(StatusCodes.Status429TooManyRequests, ProblemJsonContentType)]
public sealed class ProductsController(
    IProductQueryService productQueries,
    IProductCommandService productCommands) : ApiControllerBase
{
    private const string IfMatchHeader = "If-Match";

    /// <summary>Lists all products, ordered by name.</summary>
    [HttpGet]
    [ProducesResponseType<PagedResponse<ProductResponse>>(StatusCodes.Status200OK)]
    [ProducesResponseType<ValidationProblemDetails>(StatusCodes.Status400BadRequest, ProblemJsonContentType)]
    public async Task<ActionResult<PagedResponse<ProductResponse>>> GetProducts(
        [FromQuery] PageQuery query,
        CancellationToken cancellationToken) =>
        ToActionResult(await productQueries.ListAsync(query, cancellationToken));

    /// <summary>Gets a single product. The response carries an <c>ETag</c> header for conditional updates.</summary>
    [HttpGet("{id:int}")]
    [ProducesResponseType<ProductResponse>(StatusCodes.Status200OK)]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status404NotFound, ProblemJsonContentType)]
    public async Task<ActionResult<ProductResponse>> GetProduct(int id, CancellationToken cancellationToken)
    {
        var result = await productQueries.GetByIdAsync(id, cancellationToken);
        return result.IsSuccess ? OkWithEntityTag(result.Value) : Problem(result.Error);
    }

    /// <summary>A product's stock history (every addition, removal and correction), newest first.</summary>
    [HttpGet("{id:int}/stock-movements")]
    [ProducesResponseType<PagedResponse<StockMovementResponse>>(StatusCodes.Status200OK)]
    [ProducesResponseType<ValidationProblemDetails>(StatusCodes.Status400BadRequest, ProblemJsonContentType)]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status404NotFound, ProblemJsonContentType)]
    public async Task<ActionResult<PagedResponse<StockMovementResponse>>> GetStockMovements(
        int id,
        [FromQuery] PageQuery query,
        CancellationToken cancellationToken) =>
        ToActionResult(await productQueries.ListStockMovementsAsync(id, query, cancellationToken));

    /// <summary>Searches products whose name contains the given text (case-insensitive partial match).</summary>
    [HttpGet("search")]
    [ProducesResponseType<PagedResponse<ProductResponse>>(StatusCodes.Status200OK)]
    [ProducesResponseType<ValidationProblemDetails>(StatusCodes.Status400BadRequest, ProblemJsonContentType)]
    public async Task<ActionResult<PagedResponse<ProductResponse>>> SearchProducts(
        [FromQuery] ProductSearchQuery query,
        CancellationToken cancellationToken) =>
        ToActionResult(await productQueries.SearchByNameAsync(query, cancellationToken));

    /// <summary>Lists products whose stock lies within an inclusive range, ordered by stock (lowest first).</summary>
    [HttpGet("stock-level")]
    [ProducesResponseType<PagedResponse<ProductResponse>>(StatusCodes.Status200OK)]
    [ProducesResponseType<ValidationProblemDetails>(StatusCodes.Status400BadRequest, ProblemJsonContentType)]
    public async Task<ActionResult<PagedResponse<ProductResponse>>> GetProductsByStockLevel(
        [FromQuery] StockLevelQuery query,
        CancellationToken cancellationToken) =>
        ToActionResult(await productQueries.ListByStockLevelAsync(query, cancellationToken));

    /// <summary>Creates a product. The six-digit identifier is generated by the server.</summary>
    [HttpPost]
    [Authorize(Policy = Policies.ProductsWrite)]
    [EnableRateLimiting(RateLimitPolicies.Writes)]
    [Consumes(MediaTypeNames.Application.Json)]
    [ProducesResponseType<ProductResponse>(StatusCodes.Status201Created)]
    [ProducesResponseType<ValidationProblemDetails>(StatusCodes.Status400BadRequest, ProblemJsonContentType)]
    public async Task<ActionResult<ProductResponse>> CreateProduct(
        CreateProductRequest request,
        CancellationToken cancellationToken)
    {
        var result = await productCommands.CreateAsync(request, cancellationToken);
        if (result.IsFailure)
        {
            return Problem(result.Error);
        }

        var product = result.Value;
        SetEntityTag(product);
        return CreatedAtAction(nameof(GetProduct), new { id = product.Id }, product);
    }

    /// <summary>
    /// Replaces a product's details. Send <c>If-Match</c> with the ETag you last saw to avoid overwriting
    /// changes made by someone else (412 if the product changed in the meantime).
    /// </summary>
    [HttpPut("{id:int}")]
    [Authorize(Policy = Policies.ProductsWrite)]
    [EnableRateLimiting(RateLimitPolicies.Writes)]
    [Consumes(MediaTypeNames.Application.Json)]
    [ProducesResponseType<ProductResponse>(StatusCodes.Status200OK)]
    [ProducesResponseType<ValidationProblemDetails>(StatusCodes.Status400BadRequest, ProblemJsonContentType)]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status404NotFound, ProblemJsonContentType)]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status409Conflict, ProblemJsonContentType)]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status412PreconditionFailed, ProblemJsonContentType)]
    public async Task<ActionResult<ProductResponse>> UpdateProduct(
        int id,
        UpdateProductRequest request,
        [FromHeader(Name = IfMatchHeader)] string? ifMatch,
        CancellationToken cancellationToken)
    {
        if (!EntityTag.TryParseIfMatch(ifMatch, out var expectedVersion))
        {
            return InvalidIfMatchHeader();
        }

        var result = await productCommands.UpdateAsync(id, request, expectedVersion, cancellationToken);
        return result.IsSuccess ? OkWithEntityTag(result.Value) : Problem(result.Error);
    }

    /// <summary>Deletes a product. Optionally guarded by <c>If-Match</c>.</summary>
    [HttpDelete("{id:int}")]
    [Authorize(Policy = Policies.ProductsWrite)]
    [EnableRateLimiting(RateLimitPolicies.Writes)]
    [ProducesResponseType(StatusCodes.Status204NoContent)]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status404NotFound, ProblemJsonContentType)]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status409Conflict, ProblemJsonContentType)]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status412PreconditionFailed, ProblemJsonContentType)]
    public async Task<IActionResult> DeleteProduct(
        int id,
        [FromHeader(Name = IfMatchHeader)] string? ifMatch,
        CancellationToken cancellationToken)
    {
        if (!EntityTag.TryParseIfMatch(ifMatch, out var expectedVersion))
        {
            return InvalidIfMatchHeader();
        }

        var result = await productCommands.DeleteAsync(id, expectedVersion, cancellationToken);
        return result.IsSuccess ? NoContent() : Problem(result.Error);
    }

    // {quantity} has no route constraint on purpose: a non-numeric value is a malformed input (400), whereas
    // a non-numeric {id} simply does not identify a product (404).

    /// <summary>
    /// Removes <paramref name="quantity"/> units from stock. Atomic: fails with 409 instead of going below zero.
    /// </summary>
    [HttpPost("{id:int}/decrement-stock/{quantity}")]
    [Authorize(Policy = Policies.StockWrite)]
    [EnableRateLimiting(RateLimitPolicies.Writes)]
    [ProducesResponseType<ProductResponse>(StatusCodes.Status200OK)]
    [ProducesResponseType<ValidationProblemDetails>(StatusCodes.Status400BadRequest, ProblemJsonContentType)]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status404NotFound, ProblemJsonContentType)]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status409Conflict, ProblemJsonContentType)]
    public async Task<ActionResult<ProductResponse>> DecrementStock(
        int id,
        int quantity,
        CancellationToken cancellationToken)
    {
        var result = await productCommands.DecrementStockAsync(id, quantity, cancellationToken);
        return result.IsSuccess ? OkWithEntityTag(result.Value) : Problem(result.Error);
    }

    /// <summary>
    /// Adds <paramref name="quantity"/> units to stock. Atomic: fails with 409 instead of exceeding the maximum.
    /// </summary>
    [HttpPost("{id:int}/add-to-stock/{quantity}")]
    [Authorize(Policy = Policies.StockWrite)]
    [EnableRateLimiting(RateLimitPolicies.Writes)]
    [ProducesResponseType<ProductResponse>(StatusCodes.Status200OK)]
    [ProducesResponseType<ValidationProblemDetails>(StatusCodes.Status400BadRequest, ProblemJsonContentType)]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status404NotFound, ProblemJsonContentType)]
    [ProducesResponseType<ProblemDetails>(StatusCodes.Status409Conflict, ProblemJsonContentType)]
    public async Task<ActionResult<ProductResponse>> AddToStock(
        int id,
        int quantity,
        CancellationToken cancellationToken)
    {
        var result = await productCommands.AddToStockAsync(id, quantity, cancellationToken);
        return result.IsSuccess ? OkWithEntityTag(result.Value) : Problem(result.Error);
    }

    private OkObjectResult OkWithEntityTag(ProductResponse product)
    {
        SetEntityTag(product);
        return Ok(product);
    }

    private void SetEntityTag(ProductResponse product) =>
        Response.Headers.ETag = EntityTag.Format(product.Version);
}
