#!/usr/bin/env bash
# Deploys the web app and the gateway to the current kubectl context, from deploy/k8s/overlays/$ENVIRONMENT.
#
#   deploy/deploy.sh                                            # local: build both images, apply, wait
#   LOGS=off deploy/deploy.sh                                   # local, without the log collector (see below)
#   ENVIRONMENT=staging WEB_IMAGE=... GATEWAY_IMAGE=... deploy/deploy.sh    # what the pipeline runs
#
# The gateway sends /api to the API (the backend repository, deployed on its own) and /collect, the browser's error
# reports, to the log collector in the cluster (the infra repository: `infra.sh up logs`).
#
# Variables:
#   ENVIRONMENT                  local | staging | production (default: local)
#   WEB_IMAGE, GATEWAY_IMAGE     the images to deploy (registry/name:tag or name@sha256:digest); no local build.
#                                Without them both images are built here, which only Docker Desktop's Kubernetes
#                                can use (it runs on the same Docker engine); any other context needs them
#   LOGS=off                     no log collector: COLLECTOR_UPSTREAM becomes "", so the gateway answers /collect
#                                with 204 and drops the reports (instead of 502 errors in the browser's console)
set -euo pipefail

DEPLOY="$(cd "$(dirname "$0")" && pwd)"
FRONTEND="$(cd "$DEPLOY/.." && pwd)"
ENVIRONMENT="${ENVIRONMENT:-local}"
NAMESPACE=product-management

if [[ ! -d "$DEPLOY/k8s/overlays/$ENVIRONMENT" ]]; then
  echo "Unknown environment: $ENVIRONMENT (see deploy/k8s/overlays)" >&2
  exit 1
fi

# Unique, immutable tag per build: the commit, plus a timestamp when the working tree has local changes.
image_tag() {
  local tag
  tag="$(git -C "$FRONTEND" rev-parse --short HEAD 2>/dev/null || echo dev)"
  if [[ -n "$(git -C "$FRONTEND" status --porcelain 2>/dev/null)" ]]; then
    tag="$tag-dirty-$(date +%Y%m%d%H%M%S)"
  fi
  echo "$tag"
}

# One Kustomize `images` entry: name → reference (registry/name:tag or name@sha256:digest).
pin_image() {
  local name="$1" ref="$2"
  if [[ "$ref" == *@* ]]; then
    printf '  - name: %s\n    newName: %s\n    digest: %s\n' "$name" "${ref%@*}" "${ref#*@}"
  else
    printf '  - name: %s\n    newName: %s\n    newTag: %s\n' "$name" "${ref%:*}" "${ref##*:}"
  fi
}

CONTEXT="$(kubectl config current-context)"
echo "Deploying the web app and the gateway ($ENVIRONMENT) to Kubernetes context: $CONTEXT"

# Without WEB_IMAGE and GATEWAY_IMAGE the images are built here, and only Docker Desktop's Kubernetes can run them as
# is: it shares the Docker engine that built them. Any other cluster (staging, production) pulls from a registry.
if [[ ( -z "${WEB_IMAGE:-}" || -z "${GATEWAY_IMAGE:-}" ) && "$CONTEXT" != docker-desktop ]]; then
  echo "WEB_IMAGE and GATEWAY_IMAGE not given and the context is $CONTEXT, not docker-desktop: locally built images" >&2
  echo "would not reach this cluster. Push them to a registry and pass both, e.g." >&2
  echo "WEB_IMAGE=registry.example.com/web:1.2.3 GATEWAY_IMAGE=registry.example.com/gateway:1.2.3" >&2
  exit 1
fi

if [[ -z "${WEB_IMAGE:-}" || -z "${GATEWAY_IMAGE:-}" ]]; then
  tag="$(image_tag)"
  web="product-management/web:$tag"
  gateway="product-management/gateway:$tag"
  echo "==> Building $web and $gateway"
  # APP_VERSION: the release the web app reports with its browser errors.
  docker build --quiet --tag "$web" --build-arg APP_VERSION="$tag" "$FRONTEND" >/dev/null
  docker build --quiet --tag "$gateway" "$FRONTEND/gateway" >/dev/null
  WEB_IMAGE="$web"
  GATEWAY_IMAGE="$gateway"
fi

# The overlay with this release's images pinned (Kustomize `images`): the manifests are never edited by text.
# Kept in deploy/k8s/.build/ (not committed): the pipeline stores it as the record of what was applied.
build="$DEPLOY/k8s/.build/$ENVIRONMENT"
mkdir -p "$build"
cat > "$build/kustomization.yaml" <<EOF
# Generated by deploy/deploy.sh: the $ENVIRONMENT overlay with this release's images. Not committed.
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources: [../../overlays/$ENVIRONMENT]
images:
$(pin_image product-management/web "$WEB_IMAGE")
$(pin_image product-management/gateway "$GATEWAY_IMAGE")
EOF
if [[ "${LOGS:-on}" == off ]]; then
  cat >> "$build/kustomization.yaml" <<EOF
# LOGS=off: no log collector, the gateway drops the browser's error reports.
patches:
  - patch: |-
      apiVersion: apps/v1
      kind: Deployment
      metadata: { name: gateway, namespace: $NAMESPACE }
      spec:
        template:
          spec:
            containers:
              - name: gateway
                env:
                  - { name: COLLECTOR_UPSTREAM, value: "" }
EOF
fi

echo "==> Applying overlays/$ENVIRONMENT"
kubectl kustomize "$build" | kubectl apply -f -
kubectl -n "$NAMESPACE" rollout status deployment/web --timeout=300s
kubectl -n "$NAMESPACE" rollout status deployment/gateway --timeout=300s

echo
kubectl -n "$NAMESPACE" get pods -l 'app.kubernetes.io/name in (web, gateway)'
if [[ "$ENVIRONMENT" == local ]]; then
  if [[ "$CONTEXT" == docker-desktop ]]; then
    echo "Application: http://localhost:8080   (the gateway is a LoadBalancer Service on localhost)"
  else
    echo "Application: kubectl -n $NAMESPACE port-forward service/gateway 8080:8080   →   http://localhost:8080"
  fi
fi
